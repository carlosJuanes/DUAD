SET search_path TO ejercicio_1_postgres;

DO $$
DECLARE
	v_bill_id INTEGER;
	v_current_bill RECORD;
BEGIN 
	--SE TRABAJARA CON LA FACTURA 2 Y ANTES DE EMPEZAR. LO CAMBIAREMOS SU ESTADO
	--A PENDIENTE PARA CAMBIARLO A CANCELADO POSTERIORMENTE PARA FINES DEL EJERCICIO.
	UPDATE BILLS 
	SET STATE='PENDING'
	WHERE ID=2;
	
	-- SE MODIFICO LA TABLA BILL DETAIL YA QUE NO TENIA UNA COLUMNA PARA 
	-- MOSTRAR EL ESTADO DE ENTREGA DEL PRODUCTO,
	--LO CUAL ES REQUERIDO POR EL EJERCICIO EXTRA 1.
	ALTER TABLE BILLS_DETAIL
	ADD COLUMN DELIVER VARCHAR(20);

	--CAMBIANDO ESTADO DE PENDIENTE A CANCELADO
	UPDATE BILLS 
	SET STATE='CENCELED'
	WHERE ID=2;

	-- CAMBIANDO EL ESTADO DE ENTREGA DE LAS FACTURAS DE BILL DETAIL
	UPDATE BILLS_DETAIL	
	SET DELIVER= 'DELIVERED'
	WHERE BILL_ID IN (1, 3);

	UPDATE BILLS_DETAIL	
	SET DELIVER= 'CANCELED'
	WHERE BILL_ID=2;

	--DANDOLE EL VALOR A LA VARIABLE TEMPORAL,
	--DEL ID DE LA FACTURA CON LA QUE TRABAJAREMOS
	SELECT ID INTO v_bill_id
	FROM BILLS 
	WHERE ID = 2;

	-- REGRESANDO AL STOCK TODOS LOS PRODUCTOS QUE NO HAN SIDO 
	--ENTREGADOS DE LA FACTURA QUE ACABAMOS DE CANCELAR.
	BEGIN
		FOR v_current_bill IN
			SELECT PRODUCT_ID, QUANTITY_PURCHASED
			FROM BILLS_DETAIL
			WHERE BILL_ID=v_bill_id
		LOOP
			UPDATE PRODUCTS
			SET QUANTITY=QUANTITY+v_current_bill.QUANTITY_PURCHASED
			WHERE ID=v_current_bill.PRODUCT_ID;
		END LOOP;
	EXCEPTION
		WHEN OTHERS THEN
		RAISE NOTICE 'OCURRIO UN ERROR Y SE REVIRTIERON LOS CAMBION';
	END;

    RAISE NOTICE 'Transacción finalizada.';
	
END $$;