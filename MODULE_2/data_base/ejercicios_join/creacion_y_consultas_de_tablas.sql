SELECT BOOK.NAME, AUTHOR.NAME
FROM AUTHORS AS AUTHOR
LEFT JOIN BOOKS AS BOOK
ON AUTHOR.ID=BOOK.AUTHOR WHERE BOOK.AUTHOR IS NULL

--4 Obtenga todos los libros que han sido rentados en algún momento
SELECT BOOK.NAME, RENT.STATE
FROM BOOKS AS BOOK
LEFT JOIN RENTS AS RENT
ON BOOK.ID=RENT.BOOKS_ID WHERE RENT.STATE IS NOT NULL GROUP BY NAME

--5 Obtenga todos los libros que nunca han sido rentados
SELECT BOOK.NAME, RENT.STATE
FROM BOOKS AS BOOK
LEFT JOIN RENTS AS RENT
ON BOOK.ID=RENT.BOOKS_ID WHERE RENT.STATE IS NULL

--6 Obtenga todos los clientes que nunca han rentado un libro
SELECT CUSTOMER.NAME
FROM CUSTOMERS AS CUSTOMER
LEFT JOIN RENTS AS RENT
ON CUSTOMER.ID=RENT.CUSTOMER_ID WHERE RENT.CUSTOMER_ID IS NULL

--Obtenga todos los libros que han sido rentados y están en estado “Overdue”
SELECT BOOK.NAME, RENT.STATE
FROM BOOKS AS BOOK
LEFT JOIN RENTS AS RENT
ON BOOK.ID=RENT.BOOKS_ID WHERE RENT.STATE="Overdue"
