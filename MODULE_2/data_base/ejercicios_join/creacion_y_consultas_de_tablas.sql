--1 Obtenga todos los libros y sus autores (en caso de tenerlos)
SELECT BOOK.NAME, AUTHOR.NAME
FROM BOOKS AS BOOK
LEFT JOIN AUTHORS AS AUTHOR
ON BOOK.AUTHOR=AUTHOR.ID

--2 Obtenga todos los libros que no tienen autor
SELECT BOOK.NAME, AUTHOR.NAME
FROM BOOKS AS BOOK
LEFT JOIN AUTHORS AS AUTHOR
ON BOOK.AUTHOR=AUTHOR.ID WHERE AUTHOR.ID IS NULL

